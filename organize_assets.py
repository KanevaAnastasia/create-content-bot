#!/usr/bin/env python3
"""
Скрипт раскладки смешанных изображений по структуре ``assets/characters/<имя>/base.png`` и
``assets/locations/<имя>/base.png``.

Алгоритм (папка-источник **без рекурсии**):
1. По имени файла ищется подстрока из списков токенов (персонажи / локации).
2. Алиасы (например ``daughter`` → ``granddaughter``) приводятся к каноническим папкам.
3. Файл переносится в целевую папку; если не PNG — конвертация через Pillow в ``base.png``.
4. Пересобирается ``config.py`` в корне проекта с путями к ассетам.

Запуск:
  python3 organize_assets.py --source ./images

По умолчанию: ``--source ./images``, ``--assets-dir ./assets``.

Зависимость: ``pip install pillow``.
"""

from __future__ import annotations

import argparse
import logging
import os
from pathlib import Path
from typing import Optional

try:
    from PIL import Image, ImageOps
except ImportError as e:  # pragma: no cover
    raise SystemExit("Missing dependency. Install with: pip install pillow") from e


logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
)
logger = logging.getLogger("organize_assets")


CHARACTER_TOKENS = ["grandma", "grandfather", "grandson", "granddaughter", "daughter", "cat", "dog"]
LOCATION_TOKENS = ["kitchen", "cutting", "stove", "serving", "sink", "fridge", "table_setting", "serving_table", "fireplace"]

CHARACTER_ALIASES = {
    "daughter": "granddaughter",
}

LOCATION_ALIASES = {
    "table_setting": "serving",
    "serving_table": "serving",
    "fireplace": "stove",
}

# Pre-create these folders even if no matching files are found.
EXPECTED_CHARACTER_DIRS = ["grandma", "grandfather", "grandson", "granddaughter", "cat", "dog"]
EXPECTED_LOCATION_DIRS = ["kitchen", "cutting", "stove", "serving", "sink", "fridge"]


def classify(filename: str) -> Optional[tuple[str, str]]:
    """
    Определяет каталог назначения по подстроке в имени файла (без учёта регистра).

    Возвращает:
        ``("characters", key)`` или ``("locations", key)`` после применения алиасов,
        либо ``None``, если ни один токен не найден.
    """

    name = filename.lower()
    for token in CHARACTER_TOKENS:
        if token in name:
            return "characters", CHARACTER_ALIASES.get(token, token)
    for token in LOCATION_TOKENS:
        if token in name:
            return "locations", LOCATION_ALIASES.get(token, token)
    return None


def convert_to_png(src_path: Path, dest_png_path: Path) -> None:
    """
    Сохраняет изображение в PNG; учитывает EXIF-ориентацию через ``ImageOps.exif_transpose``.
    """
    with Image.open(src_path) as img:
        # Fix orientation using EXIF when present, then save as PNG.
        img = ImageOps.exif_transpose(img)
        img.save(dest_png_path, format="PNG")


def generate_config(assets_dir: Path) -> None:
    """
    Перезаписывает ``config.py`` в корне проекта: словарь ``ASSETS`` с относительными путями.

    Персонажи: ``{"base": "assets/characters/.../base.png"}``; локации: строка-путь к ``base.png``.
    """
    base_dir = Path(__file__).resolve().parent
    characters_dir = assets_dir / "characters"
    locations_dir = assets_dir / "locations"

    def build_characters_map(category_dir: Path) -> dict[str, dict[str, str]]:
        if not category_dir.exists():
            return {}

        out: dict[str, dict[str, str]] = {}
        for subdir in sorted([p for p in category_dir.iterdir() if p.is_dir()]):
            base_png = subdir / "base.png"
            if base_png.exists():
                # Store relative paths so `config.py` works from project root.
                out[subdir.name] = {"base": str((base_dir / base_png).relative_to(base_dir))}
        return out

    def build_locations_map(category_dir: Path) -> dict[str, dict[str, str]]:
        if not category_dir.exists():
            return {}

        out: dict[str, dict[str, str]] = {}
        for subdir in sorted([p for p in category_dir.iterdir() if p.is_dir()]):
            base_png = subdir / "base.png"
            if base_png.exists():
                item: dict[str, str] = {"base": str((base_dir / base_png).relative_to(base_dir))}
                top_view_png = subdir / "top_view.png"
                if top_view_png.exists():
                    item["top_view"] = str((base_dir / top_view_png).relative_to(base_dir))
                out[subdir.name] = item
        return out

    assets = {
        "characters": build_characters_map(characters_dir),
        "locations": build_locations_map(locations_dir),
    }

    config_path = base_dir / "config.py"

    lines = [
        '"""Auto-generated by organize_assets.py."""',
        "",
        "ASSETS = {",
        f"    'characters': {assets['characters']!r},",
        f"    'locations': {assets['locations']!r},",
        "}",
        "",
        "__all__ = ['ASSETS']",
        "",
    ]

    config_path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Updated %s", config_path)


def main() -> None:
    """
    Точка входа CLI: обходит файлы в ``--source``, переносит/конвертирует, вызывает ``generate_config``.
    """
    parser = argparse.ArgumentParser(description="Organize image assets into characters/locations structure.")
    parser.add_argument("--source", default="./images", help="Source folder with mixed images (non-recursive).")
    parser.add_argument("--assets-dir", default="./assets", help="Target assets directory.")
    args = parser.parse_args()

    source_dir = Path(args.source).expanduser().resolve()
    assets_dir = Path(args.assets_dir).expanduser().resolve()

    if not source_dir.exists():
        raise SystemExit(f"Source folder does not exist: {source_dir}")

    assets_dir.mkdir(parents=True, exist_ok=True)

    # Ensure required structure exists up-front.
    for character_key in EXPECTED_CHARACTER_DIRS:
        (assets_dir / "characters" / character_key).mkdir(parents=True, exist_ok=True)
    for location_key in EXPECTED_LOCATION_DIRS:
        (assets_dir / "locations" / location_key).mkdir(parents=True, exist_ok=True)

    moved_count = 0
    skipped_count = 0

    for path in sorted([p for p in source_dir.iterdir() if p.is_file()]):
        classification = classify(path.name)
        if classification is None:
            logger.warning("Skip (unknown category): %s", path.name)
            skipped_count += 1
            continue

        category, key = classification
        dest_dir = assets_dir / category / key
        dest_dir.mkdir(parents=True, exist_ok=True)

        dest_png_path = dest_dir / "base.png"

        # Move file first so the operation is clearly "moved", then convert if needed.
        moved_tmp_path = None
        try:
            # Replace existing to guarantee a single base.png per folder.
            # For non-PNG conversion we use a moved temporary file name.
            ext = path.suffix.lower().lstrip(".")
            if ext == "png":
                # Direct move+rename to base.png.
                os.replace(str(path), str(dest_png_path))
                logger.info("Moved %s -> %s", path.name, str(dest_png_path))
                moved_count += 1
            else:
                moved_tmp_path = dest_dir / f"source.{path.suffix.lower().lstrip('.') or 'img'}"
                # Ensure unique-ish tmp name if multiple files collide.
                if moved_tmp_path.exists():
                    moved_tmp_path = dest_dir / f"source_{path.stem}.{path.suffix.lower().lstrip('.') or 'img'}"

                os.replace(str(path), str(moved_tmp_path))
                convert_to_png(moved_tmp_path, dest_png_path)
                logger.info("Moved %s -> %s (converted to PNG)", path.name, str(dest_png_path))
                moved_tmp_path.unlink(missing_ok=True)
                moved_count += 1
        except Exception:
            logger.exception("Failed processing: %s", path)
            # If conversion fails after moving, try to leave a hint in the destination.
            if moved_tmp_path is not None and moved_tmp_path.exists():
                logger.error("Left file for inspection: %s", str(moved_tmp_path))

    logger.info("Done. moved=%s skipped=%s", moved_count, skipped_count)
    generate_config(assets_dir)


if __name__ == "__main__":
    main()

