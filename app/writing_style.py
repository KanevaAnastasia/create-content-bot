LEGACY_HUMAN_WRITING_RULES = """[CONTENT_FABRIC_WRITING_STYLE_V1]
Общие правила для создаваемого и редактируемого текста на любом языке:
Пиши естественно, конкретно и понятно выбранной аудитории. Сохраняй голос персонажа,
жанр и уместные эмоции. Реплики должны удобно произноситься; меняй длину предложений
по смыслу, избегай буквального перевода идиом. Предпочитай простые слова и глаголы.
Убирай пустой пафос, рекламные превосходные степени без оснований, канцелярит,
абстрактные рассуждения о значимости, поверхностные выводы и туманные связи.
Не используй шаблонные противопоставления «это не X, а Y», искусственные тройки,
однотипные вступления, повторные итоги и механическую замену слов синонимами.
Не приписывай мнения неназванным экспертам. Не выдумывай факты, источники, цитаты,
ссылки и личный опыт для убедительности. Художественный вымысел допустим в заданном жанре.
Убирай незаполненные заглушки, служебные комментарии, лишние заголовки, эмодзи
и выделения. Не добавляй предисловия о выполнении задания. Перед ответом молча
перечитай текст и исправь перечисленные недостатки. Не добавляй ошибки ради естественности.
Это редакционные ориентиры, а не запрет отдельных слов или знаков препинания.
Применяй их только к свободно сочиняемой прозе: сохраняй требуемые JSON-схемы,
ключи, маркеры, технические инструкции, факты, числа, тайминг и ограничения задачи.
При извлечении, транскрипции и дословном копировании не переписывай исходник.
Не меняй утверждённые реплики и цитаты без задания на их редактирование.
При проверке оценивай материал по заданным критериям; эти правила относятся
к формулировкам твоих пояснений и исправлений, а не вводят новые причины отказа.
[/CONTENT_FABRIC_WRITING_STYLE_V1]"""


# Keep previous policies byte-for-byte so saved prompts can be upgraded once.

PREVIOUS_HUMAN_WRITING_RULES = LEGACY_HUMAN_WRITING_RULES.replace("WRITING_STYLE_V1", "WRITING_STYLE_V2").replace(
    "[/CONTENT_FABRIC_WRITING_STYLE_V2]",
    """Дополнительная редактура сценариев и описаний:
Начинай с события, узнаваемого поступка или конкретной проблемы. Не объясняй зрителю,
почему тема важна. Каждый следующий фрагмент должен двигать действие или мысль.
Если задан юмор, строй шутки на поступках, деталях и противоречиях персонажа.
Не подменяй шутку случайной метафорой, набором острот или объяснением, почему смешно.
Финальная отсылка должна продолжать понятную деталь из начала, а не вводить новую.
Сохраняй причинность, время действия, голос и точку зрения рассказчика.
Не унижай зрителя. Не добавляй нравоучения, общие призывы и обещания вирусности.
Если нужен вывод, свяжи его с показанным действием и дай выполнимый следующий шаг.
В тёплой речи не злоупотребляй уменьшительными словами и не сюсюкай.
Описание публикации должно быть понятным само по себе и добавлять повод посмотреть,
а не повторять сценарий целиком. Не придумывай результат, которого нет в ролике.
В производственных описаниях сцен выбирай конкретные действия: без «возможно»,
«или» и нескольких альтернатив одного кадра. Не меняй рецепт, количества и порядок.
Молча проверь черновик: можно ли это естественно произнести; понятны ли шутки;
нет ли скачка логики, лишнего итога, повторов или натянутого сравнения.
Удали слабые фразы, затем проверь обязательные условия и формат ответа.
Эти рекомендации не меняют дословные цитаты, утверждённый текст и требования задачи.
[/CONTENT_FABRIC_WRITING_STYLE_V2]""",
)


V3_HUMAN_WRITING_RULES = PREVIOUS_HUMAN_WRITING_RULES.replace("WRITING_STYLE_V2", "WRITING_STYLE_V3").replace(
    "Это редакционные ориентиры, а не запрет отдельных слов или знаков препинания.",
    "Это обязательные редакционные требования к новой прозе. Запрет тире указан ниже.",
).replace(
    "[/CONTENT_FABRIC_WRITING_STYLE_V3]",
    """Строгая проверка новой прозы на всех языках:
Не используй тире: ни длинное, ни короткое, ни дефис с пробелами вместо тире.
Перестраивай предложения с помощью глагола, точки, запятой или двоеточия по смыслу.
Не заменяй все тире механически одной запятой. Диапазоны в новой прозе пиши словами
«от ... до ...». Сохраняй дефисы внутри слов, адресов, идентификаторов и технических данных.
Не добавляй заявления о наследии, исторической важности, общественном резонансе,
популярности, наградах и присутствии в СМИ без конкретной необходимости и основания.
Убирай пустые связи «отражает», «подчёркивает», «символизирует», если за ними нет факта.
Не заменяй изложение факта рассуждением о том, где и кем он упомянут.
Не пиши «эксперты считают» и «многие отмечают» без конкретного источника.
Не создавай секции о вызовах, перспективах и признании для заполнения объёма.
Используй простые связки и устойчивые названия. Не переименовывай один предмет
на каждом шаге ради разнообразия; не превращай заголовок темы в имя собственное.
Не используй формулы «не просто X, но и Y», «это не X, а Y» и их английские аналоги.
Не навязывай тройки, симметричные абзацы и одинаковые ритмические заготовки.
Не добавляй декоративный Markdown, жирные выделения, эмодзи, списки и заголовки,
если их не требует формат. Не заворачивай JSON в блок кода.
Не пиши Каждое Слово Заголовка С Заглавной Буквы. В новой прозе используй
обычные прямые кавычки вместо декоративных английских кавычек и апострофов.
Не вставляй в результат общение с заказчиком, комплименты, предложения продолжить,
отчёты о выполненных правилах, служебные инструкции, шаблоны и незаполненные поля.
Не выдумывай отсутствие доступных сведений и не заполняй пробелы догадками.
Не добавляй дежурные предостережения, объяснения своей даты знаний и самооправдания;
реальную неопределённость и необходимые ограничения сообщай коротко и честно.
Не придумывай ссылки, DOI, ISBN, страницы, цитаты и даты обращения к источникам.
Не заявляй о проверке источника без проверки. Не добавляй трекинг к ссылкам.
Не вставляй сломанные сноски, внутренние маркеры цитирования, шаблоны вики,
письма рецензентам, заявления о соответствии правилам или прохождении модерации.
Сохраняй голос автора, не имитируй биографию и личный опыт реального человека.
Не делай общий вывод по неподтверждённому частному примеру; не сглаживай важные детали.
Не обрывай предложения, не повторяй содержание в заключении, не рекламируй без запроса.
Смысл, логика, факты и пригодность текста важнее попыток выглядеть «не как ИИ».
Не добавляй ошибки, случайности или ложь и не обещай обход распознавания ИИ.
В технических промптах сохраняй визуальный стиль, референсы, параметры и команды.
Дословный исходник и утверждённые реплики не редактируй без отдельного задания.
[/CONTENT_FABRIC_WRITING_STYLE_V3]""",
)


# The frozen V3 prefix also occurs in saved prompts. Upgrade it without changing payload.
NARRATIVE_CLARITY_RULES = """Редакторская проверка смысла и живой речи во всех проектах:
До написания установи, кто говорит, кому, о какой конкретной ситуации и чего хочет.
Дай понятный предмет разговора до местоимений и оценок. «Сначала путался», «этот кусок»,
«стал другим», «получилось» не заменяют описание: в чём путался, что делал и что изменилось?
Если ответ уже очевиден из соседней реплики, не повторяй его. Не выдумывай детали ради конкретности.
Журналистская проверка: что произошло, с кем, при каких обстоятельствах, что этому предшествовало
и чем это закончилось. Включай только нужные для понимания ответы, не превращай их в анкету.
Каждая фраза должна продолжать предыдущую, отвечать на возникший вопрос или менять ситуацию.
Не склеивай независимые афоризмы вместо истории. Избегай рубленой цепочки «сначала... потом...
зато... теперь...», если за ней нет понятного действия. Не навязывай одинаковый ритм всем роликам.
Для озвучки мысленно произнеси весь текст от лица одного персонажа: говорит ли так человек,
не сменился ли рассказчик, понятно ли, зачем он это рассказывает? Сохраняй естественные связки.
Не проговаривай режиссёрские указания «в другой версии», «герой внизу», если персонаж сам
не обсуждает устройство кадра. Изображение может показывать результат и шутку, но не обязано
исправлять бессмысленную реплику. Конкретные поступки и речь важнее перечня модных приёмов.
Не превращай концовку в отвлечённый лозунг, самооценку или обязательную шутку. Пользовательский
дословный финал и намеренный ритмический повтор сохраняй. Не добавляй морали к уже ясной сцене.
В исторической истории сохраняй проверенные факты; не придумывай цитаты и внутренние мотивы.
В учебном объяснении называй задачу, ошибку или пример; не подменяй понятное объяснение
словами «понять связь», «выбрать способ», «изменить подход» без раскрытия их смысла.
Перед выдачей удали фразу, которая ничего не добавляет, затем проверь, не пропала ли логическая связь.
Список признаков ИИ служит поводом проверить качество, не доказательством авторства: не запрещай
обычное слово само по себе и не обещай детектору или зрителю определённый результат.
"""
HUMAN_WRITING_RULES = V3_HUMAN_WRITING_RULES.replace('WRITING_STYLE_V3', 'WRITING_STYLE_V4').replace(
    '[/CONTENT_FABRIC_WRITING_STYLE_V4]', NARRATIVE_CLARITY_RULES + '[/CONTENT_FABRIC_WRITING_STYLE_V4]'
)


def with_writing_style(prompt: str) -> str:
    """Attach all current rules to every text request; preserve the task payload."""
    text = str(prompt)
    for existing in (HUMAN_WRITING_RULES, V3_HUMAN_WRITING_RULES, PREVIOUS_HUMAN_WRITING_RULES, LEGACY_HUMAN_WRITING_RULES):
        if text.startswith(existing + "\n\n"):
            text = text[len(existing) + 2:]
            break
    return HUMAN_WRITING_RULES + "\n\n" + text
