def mode_from_label(text):
    normalized = text.strip().casefold().replace('...', '…').rstrip('…')
    return next((key for key, label in LABELS.items() if label.casefold().rstrip('…') == normalized), None)


def active_mode(session):
    if session.get('selected_project_key') == 'discipline':
        value = session.get(MODE_KEY)
        return value if value in LABELS else ''
    return ''


