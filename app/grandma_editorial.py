"""Editorial direction for the grandmother's culinary and advertising scripts."""

GRANDMA_STORY_RULES = """
МОНТАЖНАЯ ЭКОНОМИЯ:
Выбирай минимальное достаточное число сцен от 3 до 6, а не максимум диапазона.
Сначала сгруппируй рецепт по смысловым изменениям: подготовка, приготовление
или сборка, результат. Холодная нарезка с заправкой обычно требует 3 сцен:
начало, подготовка, заправка вместе с подачей. Если дополнительно нужны варка
и охлаждение, обычно достаточно 4 сцен. Это ориентиры по смыслу, не квоты.
Пятая и шестая нужны только для самостоятельного важного превращения или
приёма, который иначе станет непонятным; не выделяй сцену каждому ингредиенту.
Первый кадр может коротко показать результат, но финал должен завершить действие
или ситуацию, а не повторить то же выставление миски. Не добавляй отдельную
сцену ради подписки, реакции кота или повторного перечисления ингредиентов.
Если финал содержит только «подаю» и подписку, перенеси его в конец последней
кулинарной сцены. Финальный результат не обязан занимать отдельные восемь секунд.
У каждой сцены укажи scene_purpose: что нового узнаёт/видит зритель и почему
этот смысл нельзя без потерь объединить с соседним. Это рабочая заметка,
не реплика. Если два соседних purpose совпадают, объедини сцены.
Каждая сцена: одно простое действие, один неподвижный ракурс, один непрерывный
дубль. Внутри сцены запрещены склейки, смена планов, зум, проезды камеры,
ускорение и скачки времени. Время может пройти только МЕЖДУ сценами.
Варку, охлаждение и повторяющуюся подготовку допустимо выполнить за кадром:
в следующей сцене явно покажи продукты уже подготовленными и сохрани полный
рецепт в описании. Не пытайся показать весь рецепт руками за восемь секунд.
action описывает только простое движение внутри текущего дубля. Полную
подготовку и количества вынеси в preparation_offscreen: что уже сделано
между сценами. visual_description показывает это готовое состояние с начала
кадра. Не возвращай preparation_offscreen в список движений текущей сцены.
Бабушка и кот строго мультяшные: округлые стилизованные формы, выразительные
лица, никакого фотореализма, реалистичной кожи или натуралистичной шерсти.
Кот никогда не ест, не облизывает и не трогает человеческую еду лапами.
Для кота можно выбрать одну милую фоновую линию на весь ролик: играть с мягкой
игрушкой, сонно обнимать её, осторожно перевалиться на бок. Не требуй нового
трюка в каждой сцене. Болезнь только если задана сюжетом; без страданий ради
шутки. Падения только безопасные мультяшные, без травм. Кот не отвлекает
от основного действия бабушки и остаётся на своём месте.
Новые предметы опиши в prop_descriptions: JSON-объект стабильный_ключ -> строка
с точными формой, размером, цветом, материалом, рисунком и количеством.
В каждой сцене перечисляй только видимые предметы. Если предмет повторяется,
копируй его описание дословно, не меняй цвет/материал и не создавай дубликаты.
Одна игрушка-рыбка не превращается в живую рыбу или ингредиент.
ГОЛОС БАБУШКИ И ПРИЧИНА ДОСМОТРЕТЬ:
Бабушка разговаривает с конкретным человеком, пока делает дело. Сначала определи,
зачем ему эта история: знакомая неудача, семейный повод, желание получить вкусный
результат. Первая реплика выражает эту ситуацию, а не объявляет план съёмки.
Подготовка к празднику не означает, что праздник уже наступил. Не добавляй
поздравление без запроса пользователя. В названии блюда не перечисляй очевидные
ингредиенты без смысловой причины: достаточно «крабовый салат».
Проверяй бытовую сочетаемость слов: «майонез разошёлся по всему салату» звучит
как технический отчёт; проще «осталось всё перемешать». Не придумывай коту
желание съесть ингредиенты ради обращения к нему. Реплика про нарезку должна
выражать простую привычку бабушки, а не объяснять очевидное «все пойдут в салат».
Не заставляй бабушку произносить «покажу яркий желток», «в конце поднесу ложку»,
«досмотрите до разреза». Разрез и ложка относятся к действию камеры. Слова
«секрет», «смотри» и «в конце» сами по себе не создают интерес.
Построй одну понятную линию: жизненная ситуация, конкретное действие или полезная
деталь, видимый результат и короткая человеческая реакция. Финал отвечает на
вопрос начала. Не прячь полезный ответ ради обещания досмотреть; каждая сцена
уже даёт зрителю новое. Не выдумывай кулинарный секрет, которого нет в рецепте.
Юмор рождается из узнаваемой ситуации и характера: взгляд на кота, маленькая
заминка, короткое замечание. Не вставляй шутку в каждую фразу, не очеловечивай
боль животного и не шути над заболевшим питомцем. Не добавляй новых героев.
Говори простыми глаголами, с естественными короткими и длинными предложениями.
Не озвучивай подряд полную инструкцию «беру X граммов, промываю, варю, остужаю».
Полный рецепт и количества сохраняй в действиях; речь выбирает важную деталь
шага и отношение бабушки к происходящему. Например, если рецепт требует
остудить рис: «Рис сварю заранее, пусть остывает. Горячий в салат не кладу».
Не приписывай этому совету новых объяснений или гарантий. В середине истории
нужна хотя бы одна естественная реакция или обращение, а не шесть команд подряд.
Обращение должно быть связано с видимым поступком, не с придуманной биографией.
Не превращай речь в инструкцию на упаковке: «предназначено для», «применяю
согласно инструкции», «идеальное решение». Сведения о безопасном применении
сохраняй по смыслу, без выдуманных свойств и рекламных гарантий.
Последняя явная правка пользователя важнее старого brief и previous_scenes.
Если попросили убрать желтки, убери этот мотив из речи, действий, первого кадра
и финала; не возвращай его из старого viral brief. Утверждённые фразы сохраняй.
Перед ответом молча прочитай все реплики подряд: слышен ли разговор, а не отчёт
режиссёра? Есть ли смысл продолжать после каждой сцены? Удали повторы и пустые
обещания, проверь рецепт, персонажей и ответ финала на начало. Не сообщай
самооценку качества как доказательство будущих просмотров.
"""

GRANDMA_PRODUCTION_RULES = """
PRODUCTION FIDELITY: The approved scene text is final dialogue, not a draft to
improve. Preserve every word and speaker. Keep editorial analysis out of spoken
lines. Use only the approved cast. A product-label illustration or a negative
mention does not add a live character. Stage the first frame BEFORE the main
action, then show a small, physically executable sequence within the duration.
Each scene is ONE continuous locked-camera shot with ONE simple main action.
No cuts, inserts, montage, time jumps, time lapse, zoom, pan, tracking, reframing
or angle changes inside a scene. Preparation and elapsed time happen BETWEEN
scenes, off camera; start the next scene with the specified prepared state.
For recipe coverage, preparation_offscreen and visible prepared ingredients
establish prior steps. Do not animate those steps again inside the current shot.
Both grandma and cat are strongly stylized rounded cartoon characters, never
photorealistic humans or realistic animals, skin or fur. The cat never eats,
licks or touches human food. Preserve the same gentle background cat activity
and the exact recurring prop_descriptions; no new toys, duplicates or live fish.
Do not expand the approved scene count or add a separate outro. Keep visual interest in
the action, expression and result; do not add a new secret, food, promise or
spoken instruction. Latest user corrections override old brief motifs.
"""

