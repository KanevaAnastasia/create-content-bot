def canonical_kitchen_prop(key: str, description: str) -> str:
    name = key.strip().lower()
    if name in {"stove", "hob", "gas_stove", "cooktop", "плита", "конфорка"}:
        return GAS_STOVE_DESCRIPTION
    if name in {"oven", "духовка"}:
        return GAS_OVEN_DESCRIPTION
    return description


