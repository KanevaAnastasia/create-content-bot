def shot_direction_text(scene):
    """No extra model calls; compile only the two selected shot instructions."""
    return ' '.join(
        f'{label}: {str(scene[key]).strip()[:800]}'
        for key, label in (('performance_direction', 'Acting and attention'), ('cut_to_next', 'Planned edit boundary'))
        if isinstance(scene.get(key), str) and scene[key].strip()
    )
